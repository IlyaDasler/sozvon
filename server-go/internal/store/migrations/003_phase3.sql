-- Фаза 3: контакты, заявки, блокировки, каналы, комнаты, роли.
-- Схема 1:1 с Node-сервером (общая база, откат без миграций).
CREATE TABLE IF NOT EXISTS contacts (
	user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
	contact_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
	created_at INTEGER NOT NULL,
	chat_theme TEXT,
	wallpaper TEXT,
	PRIMARY KEY (user_id, contact_id)
);

CREATE TABLE IF NOT EXISTS friend_requests (
	from_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
	to_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
	created_at INTEGER NOT NULL,
	PRIMARY KEY (from_id, to_id)
);

CREATE TABLE IF NOT EXISTS blocks (
	user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
	blocked_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
	created_at INTEGER NOT NULL,
	PRIMARY KEY (user_id, blocked_id)
);

CREATE TABLE IF NOT EXISTS hubs (
	id INTEGER PRIMARY KEY AUTOINCREMENT,
	name TEXT NOT NULL,
	owner_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
	icon_color TEXT NOT NULL,
	icon TEXT,
	created_at INTEGER NOT NULL,
	reactions_visible INTEGER NOT NULL DEFAULT 1,
	default_perms INTEGER NOT NULL DEFAULT 31
);

CREATE TABLE IF NOT EXISTS hub_members (
	hub_id INTEGER NOT NULL REFERENCES hubs(id) ON DELETE CASCADE,
	user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
	manager INTEGER NOT NULL DEFAULT 0,
	created_at INTEGER NOT NULL,
	role_id INTEGER,
	PRIMARY KEY (hub_id, user_id)
);

CREATE TABLE IF NOT EXISTS hub_roles (
	id INTEGER PRIMARY KEY AUTOINCREMENT,
	hub_id INTEGER NOT NULL REFERENCES hubs(id) ON DELETE CASCADE,
	name TEXT NOT NULL,
	color TEXT NOT NULL,
	perms INTEGER NOT NULL,
	created_at INTEGER NOT NULL
);

CREATE TABLE IF NOT EXISTS hub_invites (
	hub_id INTEGER NOT NULL REFERENCES hubs(id) ON DELETE CASCADE,
	user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
	by_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
	created_at INTEGER NOT NULL,
	PRIMARY KEY (hub_id, user_id)
);

CREATE TABLE IF NOT EXISTS hub_bans (
	hub_id INTEGER NOT NULL REFERENCES hubs(id) ON DELETE CASCADE,
	user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
	by_id INTEGER NOT NULL,
	created_at INTEGER NOT NULL,
	PRIMARY KEY (hub_id, user_id)
);

CREATE TABLE IF NOT EXISTS hub_emojis (
	id INTEGER PRIMARY KEY AUTOINCREMENT,
	hub_id INTEGER NOT NULL REFERENCES hubs(id) ON DELETE CASCADE,
	name TEXT NOT NULL,
	file TEXT NOT NULL,
	created_by INTEGER NOT NULL,
	UNIQUE (hub_id, name)
);

CREATE TABLE IF NOT EXISTS hub_nicknames (
	hub_id INTEGER NOT NULL REFERENCES hubs(id) ON DELETE CASCADE,
	user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
	name TEXT NOT NULL,
	PRIMARY KEY (hub_id, user_id)
);

CREATE TABLE IF NOT EXISTS room_groups (
	id INTEGER PRIMARY KEY AUTOINCREMENT,
	hub_id INTEGER NOT NULL REFERENCES hubs(id) ON DELETE CASCADE,
	name TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS rooms (
	id INTEGER PRIMARY KEY AUTOINCREMENT,
	name TEXT NOT NULL,
	kind TEXT NOT NULL CHECK (kind IN ('voice', 'text')),
	owner_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
	created_at INTEGER NOT NULL,
	group_id INTEGER,
	position INTEGER,
	default_perms INTEGER NOT NULL DEFAULT 31,
	background TEXT,
	hub_id INTEGER REFERENCES hubs(id) ON DELETE CASCADE,
	private INTEGER NOT NULL DEFAULT 0
);

CREATE TABLE IF NOT EXISTS room_members (
	room_id INTEGER NOT NULL REFERENCES rooms(id) ON DELETE CASCADE,
	user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
	created_at INTEGER NOT NULL,
	role_id INTEGER,
	timeout_until INTEGER,
	PRIMARY KEY (room_id, user_id)
);

CREATE TABLE IF NOT EXISTS room_roles (
	id INTEGER PRIMARY KEY AUTOINCREMENT,
	room_id INTEGER NOT NULL REFERENCES rooms(id) ON DELETE CASCADE,
	name TEXT NOT NULL,
	color TEXT NOT NULL,
	perms INTEGER NOT NULL,
	created_at INTEGER NOT NULL
);

CREATE TABLE IF NOT EXISTS room_bans (
	room_id INTEGER NOT NULL REFERENCES rooms(id) ON DELETE CASCADE,
	user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
	by_id INTEGER NOT NULL,
	created_at INTEGER NOT NULL,
	PRIMARY KEY (room_id, user_id)
);

CREATE TABLE IF NOT EXISTS events (
	id INTEGER PRIMARY KEY AUTOINCREMENT,
	room_id INTEGER NOT NULL REFERENCES rooms(id) ON DELETE CASCADE,
	hub_id INTEGER NOT NULL REFERENCES hubs(id) ON DELETE CASCADE,
	title TEXT NOT NULL,
	starts_at INTEGER NOT NULL,
	created_by INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
	created_at INTEGER NOT NULL,
	repeat TEXT NOT NULL DEFAULT 'none',
	remind INTEGER NOT NULL DEFAULT 0,
	last_remind INTEGER,
	active INTEGER NOT NULL DEFAULT 1
);
